/**
 * Overview notes inside the root folder. They carry `lytex_generated: true`; the plugin only
 * ever rewrites notes that still carry this marker (remove it to take ownership of a note).
 */
export async function writeGeneratedNote(
  files: FileStore,
  path: string,
  title: string,
  body: string,
  overwrite: boolean,
): Promise<'created' | 'updated' | 'skipped'> {
  const existing = await files.read(path);
  if (existing !== null) {
    const p = parseNote(existing);
    if (!overwrite || p.data?.['lytex_generated'] !== true) return 'skipped';
  }
  const content = serializeNote(
    { lytex_generated: true, title },
    `# ${title}\n\n> ${msg('Automatisch erzeugt von LYTEX Operations OS. Entferne `lytex_generated` aus den Eigenschaften, um die Notiz selbst zu pflegen.', 'Generated by LYTEX Operations OS. Remove `lytex_generated` from the properties to maintain this note yourself.')}\n\n${body}`,
  );
  if (existing === null) {
    await files.create(path, content);
    return 'created';
  }
  if (existing === content) return 'skipped';
  await files.write(path, content);
  return 'updated';
}

export async function writeOverviewNotes(
  files: FileStore,
  s: LytexSettings,
  overwriteConfig: boolean,
): Promise<void> {
  const r = (p: string) => joinPath(s.rootFolder, p);
  const d = r(FOLDERS.dashboard);
  const open = msg(
    'Öffne die Ansicht über das Menüband-Symbol „LYTEX OS“ oder den Befehl „LYTEX OS: Dashboard öffnen“.',
    'Open the view via the “LYTEX OS” ribbon icon or the command “LYTEX OS: Open dashboard”.',
  );
  const dash: [string, string, string][] = [
    [
      'Home',
      msg('LYTEX – Start', 'LYTEX – Home'),
      `${open}\n\n- [[${d}/Today|${msg('Heute', 'Today')}]]\n- [[${d}/Projects|${msg('Projekte', 'Projects')}]]\n- [[${d}/Time Tracking|${msg('Zeiterfassung', 'Time tracking')}]]\n- [[${d}/Finance|${msg('Finanzen', 'Finance')}]]\n- [[${d}/Weekly Review|${msg('Wochenrückblick', 'Weekly review')}]]\n\n${msg('Alle Daten liegen als Markdown-Notizen mit Frontmatter in diesem Ordner und bleiben ohne Plugin lesbar.', 'All data are Markdown notes with frontmatter in this folder and stay readable without the plugin.')}`,
    ],
    [
      'Today',
      msg('Heute', 'Today'),
      `${open} → ${msg('„Tickets“ → „Meine Arbeit“.', '“Tickets” → “My work”.')}\n\n${msg('Die Liste wird live aus den Ticket-Notizen berechnet und hier nicht dupliziert.', 'The list is computed live from the ticket notes and not duplicated here.')}`,
    ],
    [
      'Projects',
      msg('Projekte', 'Projects'),
      `${msg('Projektordner', 'Project folder')}: [[${r(FOLDERS.projects)}]]\n\n${open} → ${msg('„Projekte“', '“Projects”')}.`,
    ],
    [
      'Time Tracking',
      msg('Zeiterfassung', 'Time tracking'),
      `${msg('Zeiteinträge', 'Time entries')}: \`${r(FOLDERS.timeEntries)}\` (${msg('eine Notiz pro Eintrag', 'one note per entry')}).\n\n${open} → ${msg('„Zeiterfassung“', '“Time tracking”')}.`,
    ],
    [
      'Finance',
      msg('Finanzen', 'Finance'),
      `${msg('Abrechnungsläufe', 'Billing batches')}: \`${r(FOLDERS.batches)}\`, ${msg('Exporte', 'exports')}: \`${r(FOLDERS.exports)}\`.\n\n${open} → ${msg('„Abrechnung“', '“Billing”')}.`,
    ],
    [
      'Weekly Review',
      msg('Wochenrückblick', 'Weekly review'),
      msg(
        'Vorlage für den Wochenrückblick:\n\n- [ ] Offene Zeiten prüfen und freigeben\n- [ ] Überfällige Tickets prüfen\n- [ ] Budgetwarnungen prüfen\n- [ ] Abrechnungsläufe exportieren / Rechnungen bestätigen\n- [ ] Wiederkehrende Aufgaben prüfen\n- [ ] Backup prüfen\n',
        'Weekly review template:\n\n- [ ] Review and approve open time\n- [ ] Check overdue tickets\n- [ ] Check budget warnings\n- [ ] Export billing batches / confirm invoices\n- [ ] Check recurring tasks\n- [ ] Check backups\n',
      ),
    ],
  ];
  for (const [file, title, body] of dash)
    await writeGeneratedNote(files, r(`${FOLDERS.dashboard}/${file}.md`), title, body, false);

  const dec = s.csv.decimalSeparator;
  const rates = [
    msg('| Einstellung | Wert |', '| Setting | Value |'),
    `|---|---|`,
    `| ${msg('Währung', 'Currency')} | ${s.currency} |`,
    `| ${msg('Standard-Stundensatz', 'Default hourly rate')} | ${centsToDecimalString(s.defaultHourlyRateCents, dec)} |`,
    `| ${msg('Standard-Tagessatz', 'Default daily rate')} | ${centsToDecimalString(s.defaultDailyRateCents, dec)} (${msg('nur bei vertraglicher Tagesabrechnung', 'only for contractual billing per day')}) |`,
    `| ${msg('Standardtag', 'Standard day')} | ${s.standardDaySeconds / 3600} ${msg('Std.', 'h')} |`,
    `| ${msg('Rundung', 'Rounding')} | ${describeRounding(s.rounding)} |`,
    '',
    msg(
      'Rangfolge: Projekt/Vertrag → Kunde → Leistung → Standard. Der angewandte Satz wird in jedem Zeiteintrag gespeichert.',
      'Precedence: project/contract → customer → service → default. The applied rate is stored in every time entry.',
    ),
    '',
    `${msg('Leistungen', 'Services')}: \`${r(FOLDERS.services)}\``,
    '',
    msg(
      'Änderungen bitte in den Plugin-Einstellungen vornehmen.',
      'Change these values in the plugin settings.',
    ),
  ].join('\n');
  await writeGeneratedNote(
    files,
    r(`${FOLDERS.configuration}/Rates.md`),
    msg('Sätze', 'Rates'),
    rates,
    overwriteConfig,
  );
  const wf = [
    msg('| Schlüssel | Bezeichnung | Kategorie |', '| Key | Label | Category |'),
    `|---|---|---|`,
    ...s.workflow.map((w) => `| ${w.key} | ${w.label} | ${w.category} |`),
    '',
    `Definition of Done: ${msg('Checkliste', 'checklist')}=${s.doneRules.requireChecklistComplete}, ${msg('Abhängigkeiten', 'dependencies')}=${s.doneRules.requireDependenciesResolved}, ${msg('Schätzung', 'estimate')}=${s.doneRules.requireEstimate}, ${msg('Zeit', 'time')}=${s.doneRules.requireTrackedTime}`,
  ].join('\n');
  await writeGeneratedNote(
    files,
    r(`${FOLDERS.configuration}/Workflow.md`),
    msg('Ticket-Workflow', 'Ticket workflow'),
    wf,
    overwriteConfig,
  );
  await writeGeneratedNote(
    files,
    r(`${FOLDERS.configuration}/Services.md`),
    msg('Leistungen', 'Services'),
    msg(
      `Leistungen liegen als einzelne Notizen in \`${r(FOLDERS.services)}\` und werden im Plugin unter „Leistungen“ gepflegt.`,
      `Services are individual notes in \`${r(FOLDERS.services)}\`, managed in the plugin under “Services”.`,
    ),
    overwriteConfig,
  );
}
